/**
 * Provider-independent AI types shared by main and renderer.
 *
 * The UI only talks to these types. Each concrete provider lives in the main
 * process (src/main/ai/providers) so credentials and system access never
 * reach the renderer.
 */
import type { ChatMessage, HandoffRecord } from './conversations'
import type { TeacherProfile, TeachingDefaults } from './teaching'

export interface ProviderCapabilities {
  /** Streams partial output via `ai.onStream`. */
  streaming: boolean
  /** A running request can be stopped with `ai.cancel`. */
  cancellation: boolean
  /** Returns the model's reply inside TeachMate (false for handoff providers). */
  returnsResponse: boolean
  /** Accepts document attachments. */
  attachments: boolean
}

export type ProviderState = 'ready' | 'needs-setup' | 'unavailable'

export interface ProviderInfo {
  id: string
  name: string
  /** `handoff` providers prepare a prompt for another app; `api` providers answer directly. */
  kind: 'handoff' | 'api'
  description: string
  capabilities: ProviderCapabilities
  state: ProviderState
  /** Human-readable status, e.g. setup instructions. */
  statusDetail: string
}

export interface ChatRequest {
  /** Generated by the renderer; used for cancellation and stream events. */
  requestId: string
  providerId: string
  conversationId: string
  conversationTitle: string
  /** Conversation history ending with the user message to answer. */
  messages: ChatMessage[]
}

export type ChatResult =
  { type: 'response'; content: string } | { type: 'handoff'; handoff: HandoffRecord }

export type ChatStreamEvent = { requestId: string; type: 'delta'; text: string }

/** A document passed to the model as context. */
export interface PromptReference {
  name: string
  text: string
  truncated: boolean
  charCount: number
}

/**
 * Provider-neutral prompt built by a feature (chat, lesson planner, …).
 * API providers map it to system + messages; the handoff provider renders it
 * as one Markdown document for Claude Code.
 */
export interface PreparedPrompt {
  /** Short label, e.g. the conversation or document title. */
  title: string
  /** Role, rules and output format (the "system" part). Markdown. */
  instructions: string
  /** Earlier turns, oldest first. */
  history: Array<{ role: 'user' | 'assistant'; content: string }>
  references: PromptReference[]
  /** The task to perform now. Markdown. */
  request: string
}

export interface AppSettings {
  /** Folder Claude Code opens in during a handoff. Null = TeachMate's handoff folder. */
  claudeCodeWorkspace: string | null
  teaching: TeachingDefaults
  /** How TeachMate addresses the teacher (dashboard greeting). */
  profile: TeacherProfile
}
