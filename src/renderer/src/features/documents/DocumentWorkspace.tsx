import { useState, type ReactNode } from 'react'
import {
  CircleCheck,
  ClipboardPaste,
  Eye,
  FileText,
  History,
  LoaderCircle,
  Pencil,
  Save,
  Send,
  Trash2,
  TriangleAlert,
} from 'lucide-react'
import type { ProviderInfo } from '@shared/ai'
import { requestScopeLabel } from '@shared/document-text'
import type { DocumentPromptPreview, DocumentRequestRecord, DocumentScope } from '@shared/documents'
import { HandoffPanel } from '@renderer/components/ai/HandoffPanel'
import { PasteReplyDialog } from '@renderer/components/ai/PasteReplyDialog'
import { controlClasses } from '@renderer/components/form/styles'
import { Badge } from '@renderer/components/ui/Badge'
import { Button } from '@renderer/components/ui/Button'
import { Card } from '@renderer/components/ui/Card'
import { CopyButton } from '@renderer/components/ui/CopyButton'
import { Dialog } from '@renderer/components/ui/Dialog'
import { IconTile } from '@renderer/components/ui/IconTile'
import { Markdown } from '@renderer/components/ui/Markdown'
import { SegmentedControl } from '@renderer/components/ui/SegmentedControl'
import { formatRelativeTime } from '@renderer/lib/format'
import { ContentChecks } from './ContentChecks'
import { ExportDocxButton } from './ExportDocxButton'
import { PromptPreviewDialog } from './PromptPreviewDialog'
import type { DocumentEditor } from './useDocumentEditor'

const SOURCE_LABEL = {
  provider: 'Generated by the AI provider',
  pasted: 'Pasted in by you',
  edited: 'Edited by you',
  computed: 'Calculated by TeachMate',
  imported: 'Imported from a file',
} as const

interface DocumentWorkspaceProps {
  editor: DocumentEditor
  provider: ProviderInfo | null
  /** e.g. "lesson plan", "objectives" */
  noun: string
  /** Tool-specific buttons for the toolbar (e.g. "Create rubric"). */
  extraActions?: ReactNode
  /** Tool-specific panels shown below the content checks. */
  children?: ReactNode
}

export function DocumentWorkspace({
  editor,
  provider,
  noun,
  extraActions,
  children,
}: DocumentWorkspaceProps) {
  const doc = editor.doc
  const [mode, setMode] = useState<'preview' | 'edit'>('preview')
  const [revision, setRevision] = useState('')
  const [pasteTarget, setPasteTarget] = useState<{ recordId: string | null } | null>(null)
  const [preview, setPreview] = useState<DocumentPromptPreview | null>(null)
  const [versionsOpen, setVersionsOpen] = useState(false)
  const [confirmDelete, setConfirmDelete] = useState(false)

  if (!doc) return null

  const latest: DocumentRequestRecord | undefined = doc.requests[0]
  const awaiting = latest?.status === 'awaiting-reply' && latest.handoff ? latest : null
  const hasContent = doc.content.trim().length > 0
  const busy = editor.busy !== null
  const handoff = provider?.capabilities.returnsResponse === false

  const requestRevision = async () => {
    const result = await editor.generate(provider, 'revise', revision)
    if (result) setRevision('')
  }

  return (
    <div className="space-y-4">
      {/* Toolbar */}
      <Card className="p-4">
        <label htmlFor="doc-title" className="sr-only">
          Document title
        </label>
        <input
          id="doc-title"
          value={doc.title}
          maxLength={160}
          onChange={(e) => editor.setTitle(e.target.value)}
          placeholder={`Untitled ${noun}`}
          className="-mx-2 block h-9 w-[calc(100%+1rem)] rounded-lg border border-transparent bg-transparent px-2 text-base font-semibold hover:border-border focus:border-primary/60 focus:outline-none"
        />
        <div className="mt-2 flex flex-wrap items-center gap-2">
          <SaveStatus
            dirty={editor.dirty}
            persisted={editor.persisted}
            saving={editor.busy === 'saving'}
          />
          <span className="flex-1" />
          <Button
            size="sm"
            variant={editor.dirty ? 'primary' : 'secondary'}
            onClick={() => void editor.save()}
            disabled={busy}
          >
            <Save className="size-4" aria-hidden />
            Save
          </Button>
          {hasContent && <CopyButton text={doc.content} label={`Copy ${noun}`} />}
          <ExportDocxButton
            editor={editor}
            disabled={!hasContent}
            withVariants={doc.kind === 'assessment'}
          />
          {extraActions}
          <Button
            size="sm"
            variant="ghost"
            onClick={() => setVersionsOpen(true)}
            disabled={doc.versions.length === 0}
            title="Earlier versions"
          >
            <History className="size-4" aria-hidden />
            {doc.versions.length}
          </Button>
          <Button
            size="sm"
            variant="ghost"
            onClick={() => setConfirmDelete(true)}
            aria-label={`Delete ${noun}`}
            title={`Delete ${noun}`}
          >
            <Trash2 className="size-4" aria-hidden />
          </Button>
        </div>
      </Card>

      {editor.error && (
        <div
          role="alert"
          className="flex items-start gap-2 rounded-xl border border-primary/30 bg-primary-soft px-4 py-3 text-sm text-primary-soft-foreground"
        >
          <TriangleAlert className="mt-0.5 size-4 shrink-0" aria-hidden />
          <span className="flex-1">{editor.error}</span>
          <button
            type="button"
            className="cursor-pointer text-xs font-medium underline-offset-2 hover:underline"
            onClick={() => editor.setError(null)}
          >
            Dismiss
          </button>
        </div>
      )}

      {editor.busy === 'generating' && (
        <Card className="flex items-center gap-3 p-4 text-sm text-muted-foreground" role="status">
          <LoaderCircle className="size-4 animate-spin" aria-hidden />
          {handoff ? 'Preparing your prompt for Claude Code…' : `Generating your ${noun}…`}
        </Card>
      )}

      {awaiting?.handoff && editor.busy !== 'generating' && (
        <HandoffPanel
          handoff={awaiting.handoff}
          createdAt={awaiting.createdAt}
          busy={busy}
          context="document"
          title={
            awaiting.scope
              ? `${requestScopeLabel(awaiting.scope)} sent to Claude Code`
              : awaiting.action === 'revise'
                ? 'Revision sent to Claude Code'
                : 'Continue in Claude Code'
          }
          onPasteReply={() => setPasteTarget({ recordId: awaiting.id })}
          onPrepareAgain={() =>
            void editor.generate(provider, awaiting.action, awaiting.instruction, awaiting.scope)
          }
        />
      )}

      {/* Content */}
      {hasContent ? (
        <Card className="overflow-hidden">
          <div className="flex flex-wrap items-center justify-between gap-2 border-b border-border px-4 py-2.5">
            <SegmentedControl
              label="View"
              value={mode}
              onChange={setMode}
              options={[
                { value: 'preview', label: 'Preview', icon: Eye },
                { value: 'edit', label: 'Edit', icon: Pencil },
              ]}
            />
            <span className="text-xs text-muted-foreground">
              {doc.contentSource ? SOURCE_LABEL[doc.contentSource] : ''}
            </span>
          </div>
          {mode === 'preview' ? (
            <div className="max-h-[70vh] overflow-y-auto px-6 py-5" data-role="document-preview">
              <Markdown>{doc.content}</Markdown>
            </div>
          ) : (
            <textarea
              value={doc.content}
              onChange={(e) => editor.setContent(e.target.value)}
              aria-label={`Edit ${noun} (Markdown)`}
              spellCheck
              className="block h-[70vh] w-full resize-none bg-surface px-6 py-5 font-mono text-xs leading-6 focus:outline-none"
            />
          )}
        </Card>
      ) : (
        !awaiting &&
        editor.busy !== 'generating' && (
          <Card className="flex flex-col items-center px-6 py-14 text-center">
            <IconTile icon={FileText} size="lg" tone="muted" />
            <h2 className="mt-4 text-base font-semibold">No {noun} yet</h2>
            <p className="mt-1 max-w-sm text-sm text-muted-foreground">
              Fill in the form and choose{' '}
              <span className="font-medium text-foreground">
                {handoff ? 'Prepare for Claude Code' : 'Generate'}
              </span>
              . {handoff && 'When Claude replies, paste the reply here to edit and save it.'}
            </p>
            <Button
              variant="ghost"
              size="sm"
              className="mt-4"
              onClick={() => setPasteTarget({ recordId: null })}
            >
              <ClipboardPaste className="size-4" aria-hidden />
              Paste existing content instead
            </Button>
          </Card>
        )
      )}

      {hasContent && <ContentChecks doc={doc} />}

      {hasContent && children}

      {/* Revision */}
      {hasContent && (
        <Card className="p-4">
          <label htmlFor="revision" className="text-sm font-medium">
            Ask for changes
          </label>
          <p className="mt-0.5 text-xs text-muted-foreground">
            Describe what to change. The current {noun} and your form details are sent along.
          </p>
          <textarea
            id="revision"
            value={revision}
            onChange={(e) => setRevision(e.target.value)}
            rows={3}
            maxLength={4000}
            placeholder="e.g. Add a pair activity for learners without computers, and make the evaluation 10 items."
            className={controlClasses(false, 'mt-2 resize-y py-2 leading-6')}
          />
          <div className="mt-2 flex flex-wrap justify-end gap-2">
            <Button
              variant="ghost"
              size="sm"
              disabled={!revision.trim() || busy}
              onClick={() =>
                void editor.previewPrompt('revise', revision).then((p) => p && setPreview(p))
              }
            >
              <Eye className="size-4" aria-hidden />
              Preview prompt
            </Button>
            <Button
              size="sm"
              disabled={!revision.trim() || busy}
              onClick={() => void requestRevision()}
            >
              <Send className="size-4" aria-hidden />
              {handoff ? 'Send revision to Claude Code' : 'Revise'}
            </Button>
          </div>
        </Card>
      )}

      <PromptPreviewDialog
        preview={preview}
        onClose={() => setPreview(null)}
        sendLabel={handoff ? 'Send revision to Claude Code' : 'Revise'}
        onSend={() => {
          setPreview(null)
          void requestRevision()
        }}
      />

      <PasteReplyDialog
        open={pasteTarget !== null}
        onClose={() => setPasteTarget(null)}
        title={pasteTarget?.recordId ? 'Paste Claude’s reply' : `Paste existing ${noun}`}
        description={
          pasteTarget?.recordId
            ? awaiting?.id === pasteTarget.recordId && awaiting.scope
              ? scopedPasteDescription(awaiting.scope)
              : `Copy Claude’s reply from Claude Code and paste it here. It becomes the ${noun}; the previous version is kept in history.`
            : `Paste ${noun} text you already have (Markdown or plain text) to edit and save it here.`
        }
        confirmLabel={
          pasteTarget?.recordId &&
          awaiting?.id === pasteTarget.recordId &&
          awaiting.scope?.type === 'revision'
            ? 'Use as revised plan'
            : `Use as ${noun}`
        }
        onSave={async (content) => {
          await editor.applyReply(pasteTarget?.recordId ?? null, content)
          setPasteTarget(null)
          setMode('preview')
        }}
      />

      <Dialog
        open={versionsOpen}
        onClose={() => setVersionsOpen(false)}
        title="Earlier versions"
        description="Previous contents are kept when a reply replaces the document. Restoring keeps the current version in history."
      >
        <ul className="divide-y divide-border">
          {doc.versions.map((v, i) => (
            <li key={`${v.createdAt}-${i}`} className="flex items-center gap-3 py-3">
              <div className="min-w-0 flex-1">
                <p className="text-sm font-medium">{SOURCE_LABEL[v.source]}</p>
                <p className="truncate text-xs text-muted-foreground">
                  {formatRelativeTime(new Date(v.createdAt))} · {v.content.slice(0, 80)}
                </p>
              </div>
              <Button
                size="sm"
                variant="secondary"
                onClick={() => {
                  setVersionsOpen(false)
                  void editor.restoreVersion(i)
                }}
              >
                Restore
              </Button>
            </li>
          ))}
        </ul>
      </Dialog>

      <Dialog
        open={confirmDelete}
        onClose={() => setConfirmDelete(false)}
        title={`Delete this ${noun}?`}
        description={`“${doc.title}” will be permanently removed from this device.`}
        footer={
          <>
            <Button variant="ghost" size="sm" onClick={() => setConfirmDelete(false)}>
              Cancel
            </Button>
            <Button
              size="sm"
              onClick={() => {
                setConfirmDelete(false)
                void editor.remove()
              }}
            >
              <Trash2 className="size-3.5" aria-hidden />
              Delete
            </Button>
          </>
        }
      />
    </div>
  )
}

function scopedPasteDescription(scope: DocumentScope): string {
  switch (scope.type) {
    case 'activity':
      return `Copy Claude’s reply from Claude Code and paste it here. It replaces Activity ${scope.index} only; the previous version is kept in history.`
    case 'alternatives':
      return 'Copy Claude’s reply from Claude Code and paste it here. The new activities are added after the current ones; the previous version is kept in history.'
    case 'revision':
      return 'Copy Claude’s reply from Claude Code and paste it here. It is kept as a separate revised lesson plan; the original plan and this review are not changed.'
  }
}

function SaveStatus({
  dirty,
  persisted,
  saving,
}: {
  dirty: boolean
  persisted: boolean
  saving: boolean
}) {
  if (saving) return <Badge>Saving…</Badge>
  if (!persisted) return <Badge>Not saved yet</Badge>
  if (dirty) return <Badge tone="primary">Unsaved changes</Badge>
  return (
    <Badge tone="success">
      <CircleCheck className="size-3" aria-hidden />
      Saved
    </Badge>
  )
}
